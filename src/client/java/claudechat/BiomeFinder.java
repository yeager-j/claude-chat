package claudechat;

import net.minecraft.core.Holder;
import net.minecraft.core.QuartPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.util.Mth;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.BiomeResolver;
import net.minecraft.world.level.biome.BiomeSource;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Set;

/**
 * Finds several patches of a biome, nearest first: like /locate biome, which stops at the first hit. Samples the
 * seed's biome noise on the same grid /locate uses (every 32 blocks across, every 64 blocks up and down, heights
 * nearest the player first), outward in square rings. A hit closer than {@code minSpacing} to an earlier one is the
 * same patch and is skipped. Nothing is generated or loaded, so it's safe off the server thread; worlds generated by
 * older versions keep their old biomes where already generated.
 */
public final class BiomeFinder {
	private static final int STEP = 32;
	private static final int VERTICAL_STEP = 64;
	/** /locate biome's radius is 6400 blocks; a whole 30000-block search is about 2.8M columns. */
	private static final long MAX_SAMPLES = 20_000_000L;

	public record Found(String biome, int x, int y, int z, double distance) {
	}

	public record Result(List<Found> found, boolean truncated) {
	}

	private BiomeFinder() {
	}

	public static Result find(ServerLevel level, Set<Holder<Biome>> biomes, double ox, double oy, double oz, int maxDistance,
		int minSpacing, int limit) {
		BiomeSource source = level.getChunkSource().getGenerator().getBiomeSource();
		BiomeResolver resolver = source.createCachingResolver(level.getChunkSource().randomState());
		int[] ys = Mth.outFromOrigin((int) Math.floor(oy), level.getMinY() + 1, level.getMaxY() + 1, VERTICAL_STEP).toArray();
		int originX = (int) Math.floor(ox);
		int originZ = (int) Math.floor(oz);
		int maxRing = maxDistance / STEP + 1;

		List<Found> found = new ArrayList<>();
		long samples = 0;
		for (int ring = 0; ring <= maxRing; ring++) {
			for (int dx = -ring; dx <= ring; dx++) {
				for (int dz = -ring; dz <= ring; dz++) {
					if (Math.abs(dx) != ring && Math.abs(dz) != ring) {
						continue;
					}
					int x = originX + dx * STEP;
					int z = originZ + dz * STEP;
					double distance = Math.sqrt(Math.pow(x - ox, 2) + Math.pow(z - oz, 2));
					if (distance > maxDistance || near(found, x, z, minSpacing)) {
						continue;
					}
					for (int y : ys) {
						samples++;
						Holder<Biome> biome = resolver.getNoiseBiome(QuartPos.fromBlock(x), QuartPos.fromBlock(y), QuartPos.fromBlock(z));
						if (biomes.contains(biome)) {
							found.add(new Found(RegistryQuery.id(biome), x, y, z, distance));
							break;
						}
					}
				}
			}
			// Every column in the next ring is at least (ring + 1) * STEP away, so once enough hits are closer, stop.
			if (found.size() >= limit) {
				found.sort(Comparator.comparingDouble(Found::distance));
				if (found.get(limit - 1).distance() <= (ring + 1) * STEP) {
					break;
				}
			}
			if (samples > MAX_SAMPLES) {
				found.sort(Comparator.comparingDouble(Found::distance));
				return new Result(List.copyOf(found.subList(0, Math.min(limit, found.size()))), true);
			}
		}
		found.sort(Comparator.comparingDouble(Found::distance));
		return new Result(List.copyOf(found.subList(0, Math.min(limit, found.size()))), false);
	}

	private static boolean near(List<Found> found, int x, int z, int spacing) {
		for (Found f : found) {
			if (Math.abs(f.x() - x) < spacing && Math.abs(f.z() - z) < spacing
				&& Math.pow(f.x() - x, 2) + Math.pow(f.z() - z, 2) < (double) spacing * spacing) {
				return true;
			}
		}
		return false;
	}
}
